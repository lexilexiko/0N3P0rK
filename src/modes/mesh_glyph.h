static const uint16_t MESH_GLYPH_N = sizeof(MESH_GLYPHS) / sizeof(MESH_GLYPHS[0]);

static const uint8_t* meshGlyph(uint16_t cp) {
    int lo = 0;
    int hi = (int)MESH_GLYPH_N - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint16_t c = MESH_GLYPHS[mid].cp;
        if (c == cp) return MESH_GLYPHS[mid].col;
        if (c < cp) lo = mid + 1;
        else hi = mid - 1;
    }
    return nullptr;
}
