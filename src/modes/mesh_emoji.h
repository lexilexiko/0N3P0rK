static const uint16_t MESH_EMOJI_GLYPH_N =
    sizeof(MESH_EMOJI_GLYPHS) / sizeof(MESH_EMOJI_GLYPHS[0]);

static const uint8_t* meshEmojiGlyph(uint32_t cp) {
    int lo = 0;
    int hi = (int)MESH_EMOJI_GLYPH_N - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint32_t c = MESH_EMOJI_GLYPHS[mid].cp;
        if (c == cp) return MESH_EMOJI_GLYPHS[mid].col;
        if (c < cp) lo = mid + 1;
        else hi = mid - 1;
    }
    return nullptr;
}
